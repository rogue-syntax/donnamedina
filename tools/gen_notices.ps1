Add 'VSTGUI' (Strip (Get-Content -Encoding UTF8 (Join-Path $sdk 'vstgui4\LICENSE')))

Add 'mda DX10 (the synthesis engine this plug-in is derived from)' (Strip (Lines (Join-Path $root 'source\mdaDX10Processor.h') 7 13))

Add 'NanoVG' (Strip (Lines (Join-Path $root 'source\nanovg.c') 2 17))

$glew = Join-Path $root 'external\glew\include\GL\glew.h'
Add 'GLEW (The OpenGL Extension Wrangler Library)' ((Strip (Lines $glew 1 31)) + @('') + (Strip (Lines $glew 33 54)) + @('') + (Strip (Lines $glew 56 76)))

# Monocypher is dual-licensed (2-clause BSD or CC-0); we use it under the BSD licence (its lines 14..41).
Add 'Monocypher (license signature check), used under its 2-clause BSD licence' (Strip (Lines (Join-Path $root 'external\monocypher\LICENCE.md') 14 41))

Add 'DejaVu Sans Mono (user interface font)' (Strip (Get-Content -Encoding UTF8 (Join-Path $root 'licenses\DejaVu-LICENSE.txt')))

$notices = Join-Path $root 'licenses\THIRD-PARTY-NOTICES.txt'
[IO.File]::WriteAllText($notices, (($sec -join "`r`n").TrimEnd() + "`r`n"))

# creditsText.h: one string per paragraph (lines joined, NanoVG wraps them); "## " starts a heading.
# A line that starts a list item ("* ", "- ", "1. ") starts a new paragraph; its indented
# continuation lines join it.
$paras = New-Object System.Collections.Generic.List[string]
$cur = ''
foreach ($l in (Get-Content -Encoding UTF8 $notices)) {
	if ($l.Trim() -eq '') { if ($cur) { $paras.Add($cur); $cur = '' }; continue }
	if ($l -match '^## ' -or $l -match '^\s*([*-]|\d+\.)\s') {
		if ($cur) { $paras.Add($cur) }
		$cur = $l.Trim()
		if ($l -match '^## ') { $paras.Add($cur); $cur = '' }
		continue
	}
	$cur = if ($cur) { "$cur $($l.Trim())" } else { $l.Trim() }
}
if ($cur) { $paras.Add($cur) }
# ASCII only, except the trademark sign: UTF-8 bytes, then the literal is closed and reopened so the
# \xA2 escape can't run into the next character
function CEsc([string]$s) { (($s -replace '\\', '\\' -replace '"', '\"') -replace '[^\x20-\x7E™]', '?').Replace($tm, '\xE2\x84\xA2" "') }
$h = New-Object System.Text.StringBuilder
[void]$h.Append("#pragma once`r`n// Generated by tools/gen_notices.ps1 from licenses/THIRD-PARTY-NOTICES.txt - do not edit.`r`n")
[void]$h.Append("// The about screen's CREDITS page (NVGView::drawMoreInfoWindow): one paragraph per entry,`r`n// ""## "" starts a heading.`r`n`r`nnamespace credits {`r`nstatic const char* const kText[] = {`r`n")
foreach ($p in $paras) { [void]$h.Append("`t""" + (CEsc $p) + """,`r`n") }
[void]$h.Append("};`r`nconstexpr int kCount = sizeof(kText) / sizeof(kText[0]);`r`n} // namespace credits`r`n")
[IO.File]::WriteAllText((Join-Path $root 'source\creditsText.h'), $h.ToString())
"notices: $($sec.Count) lines; credits: $($paras.Count) paragraphs"
