# Builds licenses/THIRD-PARTY-NOTICES.txt from the licence texts in the sources it covers, then
# source/creditsText.h (the CREDITS page of the about screen) from that file.
# Run from the project root:  powershell -ExecutionPolicy Bypass -File tools\gen_notices.ps1
# The SDK paths are relative to the project (..\..\..\..\.. = VST3_SDK).
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$sdk = (Resolve-Path (Join-Path $root '..\..\..\..\..')).Path

function Strip([string[]]$lines) {
	# drop comment decoration: leading //, /*, */, **, *, and the box borders
	$out = foreach ($l in $lines) {
		if ($l -match '^\s*\$Id.*\$\s*$') { continue }  # version-control tags
		# typographic punctuation -> ASCII (the UI font table and the C strings stay ASCII)
		# (character codes, not literals: this file has no BOM, so Windows PowerShell reads it as ANSI)
		$l = $l.Replace([string][char]0x2018, "'").Replace([string][char]0x2019, "'")
		$l = $l.Replace([string][char]0x201C, '"').Replace([string][char]0x201D, '"')
		$l = $l.Replace([string][char]0x2013, '-').Replace([string][char]0x2014, '-')
		$s = $l -replace '^\s*(//|/\*+|\*+/|\*\*|\*)\s?', ''
		$s = $s -replace '\s*\*+\s*$', ''
		$s = $s -replace '^ (?=\S)', ''
		if ($s -match '^-{5,}$') { continue }
		$s.TrimEnd()
	}
	# trim leading / trailing blank lines
	$a = @($out)
	while ($a.Count -and $a[0] -eq '') { $a = $a[1..($a.Count - 1)] }
	while ($a.Count -and $a[-1] -eq '') { $a = $a[0..($a.Count - 2)] }
	return $a
}
function Lines($path, $from, $to) { (Get-Content -Encoding UTF8 $path)[($from - 1)..($to - 1)] }

$sec = New-Object System.Collections.Generic.List[string]
function Add($title, [string[]]$body) {
	$sec.Add("## $title")
	$sec.Add('')
	foreach ($b in $body) { $sec.Add($b) }
	$sec.Add('')
}

