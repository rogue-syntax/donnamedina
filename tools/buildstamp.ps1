# Writes source\buildstamp.cpp (not in git): the branch, short commit and build time, shown in the
# editor's About window under the version, so you can tell which build a host has loaded.
# Run by the project's pre-build step:  powershell -NoProfile -ExecutionPolicy Bypass -File tools\buildstamp.ps1 <project dir>
param([string]$ProjectDir = (Split-Path -Parent $PSScriptRoot))

$branch = "unknown"
$commit = "unknown"
try {
    $b = & git -C $ProjectDir rev-parse --abbrev-ref HEAD 2>$null
    $c = & git -C $ProjectDir rev-parse --short HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and $b -and $c) { $branch = $b.Trim(); $commit = $c.Trim() }
} catch { }
$stamp = "$branch $commit  " + (Get-Date -Format "yyyy-MM-dd HH:mm")

$out = Join-Path $ProjectDir "source\buildstamp.cpp"
$text = @"
// Generated by tools\buildstamp.ps1 at every build (pre-build step). Not in git; do not edit.
#include "buildstamp.h"
const char* const kBuildStamp = "$stamp";
"@
# rewrite only when it changes (within a minute nothing is recompiled)
$old = if (Test-Path $out) { [IO.File]::ReadAllText($out) } else { "" }
if ($old -ne $text) { [IO.File]::WriteAllText($out, $text, (New-Object Text.ASCIIEncoding)) }
Write-Host "build stamp: $stamp"
